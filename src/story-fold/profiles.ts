/**
 * **场景档**：骨架和证据器是共用的，阈值和证据组合不是。
 *
 * 一个阈值通吃三种「同质」必然两头不讨好——调到能并转载，就会把同一作者的两条不同内容
 * 也并掉。所以每个场景一份自己的档，改档只影响那一个场景（设计见
 * `docs/superpowers/specs/2026-08-13-same-story-folding-design.md` §3.2）。
 */

/**
 * **比正文那一档**的参数（`./text-fold.ts`）。缺席 = 这个场景只比链接和标题，一次网络请求都不发。
 */
export interface TextFoldSettings {
  /**
   * 两篇正文里**最长的那一段一模一样的连续文字**超过多少字，就认它们是同一篇稿子
   * （量法与实测表见 `src/text/shingle.ts` 的 `longestSharedRun`）。
   *
   * 130：15 次真实搜索（中英文新闻 / 技术问答 / 论坛）的跨站实测里，**各写各的同一件事**
   * 最高 60 字，**真转载**最低 94、其次 142；夹在中间的是**技术页面共享的机器输出**——两篇
   * 毫不相干的文章共享同一段 Python traceback 就有 125 字、共享 `nvidia-smi` 表头有 105 字。
   * 130 卡在 125 和 142 之间：把实测撞到的机器输出挡在外面，一条真转载都没多漏。
   *
   * **英文不另设一档**：归一化去掉空格后 130 字在英文里只有 20 来个词，听着短，但实测独立
   * 英文报道最高 54 字，和中文同一量级。分不开的是体裁不是语言——更长的堆栈能共享得更多，
   * **这一类没有任何字数门槛挡得住**（表和讨论见 `src/text/shingle.ts` 的 `longestSharedRun`）。
   *
   * 这一档**宁可漏**：漏掉的那对还会落到第 3 档（问模型）手里，而这一档并错了没有下一站。
   *
   * **不用草图 Jaccard**：网页正文拖着一身样板，整篇算的相似度对真转载只有 0.076–0.14，
   * 和「各写各的」（0.006–0.016）之间没有能安全下刀的地方。
   */
  minSharedChars: number
  /**
   * 一次搜索最多抓几篇正文。**这是成本的硬上限**，不是性能调优：一次搜索十几条结果，
   * 抓满就是十几次网络请求。12 覆盖 MCP 那边 `slice(0, 10)` 真正会被看到的那一段还有余量，
   * 超出的按输入序（＝相关性序）截断——排在后面的本来也很少被读。
   */
  maxFetches: number
  /** 并发抓几篇。放开了打既慢又容易被上游限速。 */
  concurrency: number
  /** 单篇的超时。到点当作「判不了」，那一对保持原样。 */
  timeoutMs: number
}

/**
 * **问模型那一档**的参数（`./semantic-fold.ts`）。缺席 = 这个场景不问模型，一次调用都不发。
 *
 * 它治的是第 2 档治不了的那一类：**同一篇通稿被 AI 重写过**。实测改写稿和原稿的最长共享块
 * 只有 17 字，而「各写各的同一件事」是 6–11 字——这两个数挨在一起，靠字数门槛永远分不开。
 */
export interface SemanticFoldSettings {
  /**
   * 一次最多把几篇递给模型。**这是成本的硬上限**：一次搜索只发一发调用，篇数决定这发调用多大。
   * 12 和第 2 档的 `maxFetches` 对齐——第 3 档只吃第 2 档抓到的正文，多了也没有。
   */
  maxArticles: number
  /**
   * 每篇转成文字前多少字。600 是照「够判出是哪件事」定的：新闻的主体、时间、动作都在导语里，
   * 再往下是细节和样板，喂进去只是把 token 变贵、把重点冲淡。
   */
  charsPerArticle: number
  /**
   * 模型自报的把握要到多少才算数。0.8：这一档**宁可漏，不可错**——漏了只是同一件事占两格
   * （今天的样子），错了是把用户要找的那条藏起来。模型的置信度校准得不准，所以它不是一把
   * 精密的尺，只是一道「模型自己都不太确定的组一律丢掉」的粗闸门。
   */
  minConfidence: number
  /** 等模型回话的上限。到点当作「判不了」，这一轮不做语义判定，搜索结果照常返回。 */
  timeoutMs: number
}

export interface FoldProfile {
  /** 标题 Dice 过这条线才认「同一件事」。 */
  titleThreshold: number
  /**
   * **同站的一对，标题像不再单独成立**——它降级成「疑似」，要第 2 档抓正文确认才算数
   * （跨站不受影响，判据见 `./fold.ts` 的 `titleNeedsTextConfirm`）。
   *
   * 为什么只对同站：搜狐号/百家号/网易号这类「一个域名、无数个发布者」的平台上，同一个
   * 栏目天天更新、标题只换日期，实测 `www.sohu.com/a/613889193_121124005` 与
   * `.../577012683_121124005` 两天的「每日一练｜时事政治模拟题」Dice 0.857 越过 0.85 阈值，
   * 题目却完全不同，而 `serialConflict` 对它无能为力（标题里一个号都没有）。跨站不存在这种
   * 「同一个栏目连载」的形态，标题像就直接合，一分钱不花——那正是第 1 档存在的价值。
   *
   * **这一格不由场景档写死，由 `withSameHostTextConfirm` 按第 2 档到底可不可用来置位**：
   * 第 2 档缺席时降级就是净损失（同站的标题相同转载再也合不了，比今天更差）。
   */
  sameHostTitleNeedsText?: boolean
  /**
   * 比正文那一档。**缺席 = 不比正文**（不发任何网络请求），行为退回只看链接和标题。
   */
  text?: TextFoldSettings
  /**
   * 问模型那一档。**缺席 = 不问模型**（不发任何调用）。它依赖上一档抓到的正文，
   * `text` 缺席时它自然也判不了任何一对。
   */
  semantic?: SemanticFoldSettings
}

/**
 * 搜索结果折叠（档 A）。0.85 对齐网盘认集 title stage 的阈值——同一把尺，
 * 同一个量级的严格度。**数字签名一票否决**（`serialConflict`）是它敢用这么低阈值的前提，
 * 也是「同一档节目的两集不会被并」的唯一防线。
 */
export const SEARCH_PROFILE: FoldProfile = {
  titleThreshold: 0.85,
  /**
   * **默认开着**：换来的是「标题被改写过的转载」不再各占一格。只在**免费的两道判据都没判出来**
   * 时才发请求，抓不到就当没抓（判不了 ≠ 不像），所以最坏情况只是白等一个超时。
   *
   * **这里的数只管单篇，管不住整段**：12 篇 ÷ 4 并发 × 8s = 24s，加上第 3 档还能再叠 20s，
   * 实测冷跑整段折叠能吃掉 20–40s。整段的上限在别处——`web-search-ladder.ts` 的
   * `FOLD_BUDGET_MS`（8s，到点就把没折的原样给出去）。
   */
  text: { minSharedChars: 130, maxFetches: 12, concurrency: 4, timeoutMs: 8_000 },
  /**
   * **默认开着**，理由和上面那档同源、请求更少：它一个网络抓取都不发（只吃上一档已经抓到的
   * 正文），一次搜索最多一发模型调用。但**墙钟不便宜**——这 20s 是接在上一档之后的，两档合起来
   * 由 `FOLD_BUDGET_MS` 的 8s 总预算收口。没配 LLM / 调用失败 / 超时一律「判不了」，结果照原样返回。
   */
  semantic: { maxArticles: 12, charsPerArticle: 600, minConfidence: 0.8, timeoutMs: 20_000 },
}
